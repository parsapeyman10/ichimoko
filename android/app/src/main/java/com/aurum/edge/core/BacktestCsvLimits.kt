package com.aurum.edge.core

/**
 * سقف‌ها و پیام‌های «فایل سنگین» — به‌عمد در لایهٔ `core` و کاملاً مستقل از اندروید.
 *
 * چرا جدا شد؟ این اعداد باید هم در `BacktestDataStore` (که به `Context` اندروید وابسته است)
 * استفاده شوند و هم در آزمون‌های JUnit قابل بررسی باشند. اگر داخل آن کلاس می‌ماندند، آزمون
 * آن‌ها در محیط بدون اندروید کامپایل نمی‌شد و عملاً هیچ‌وقت آزموده نمی‌شدند.
 *
 * ── چرا این عددها؟ ─────────────────────────────────────────────────────────────
 * اندازه‌گیری واقعی: ۱۰۰٬۰۰۰ کندل M15 ≈ ۶٫۵ مگابایت متن و ≈ ۶ مگابایت سری کندل در heap.
 * پس ۲۴ مگابایت ≈ ۳۷۰٬۰۰۰ کندل ≈ ۲۵ مگابایت حافظه؛ روی گوشی معمولی جا می‌شود و بالاتر از
 * آن خطر واقعی OutOfMemory است. سقف «کاراکتر» و «بایت» عمداً یکی است تا کاربر دو عدد متناقض
 * نبیند.
 */
object BacktestCsvLimits {

    /** سقف بایت هنگام خواندن فایل. */
    const val MAX_CSV_BYTES: Long = 24_000_000L

    /** سقف کاراکتر متن؛ باید با [MAX_CSV_BYTES] بخواند. */
    const val MAX_CSV_CHARS: Int = 24_000_000

    /** تخمین کندل از روی بایت، برای گفتن «چند کندل» در پیام خطا (هر کندل ≈ ۶۵ بایت). */
    const val APPROX_BYTES_PER_BAR: Int = 65

    /**
     * پیام صریح برای فایل سنگین: چه اتفاقی افتاد، چرا، و **چه کاری** درست است.
     *
     * رد کردنِ خشک بدون راهنمایی («حجم زیاد است») همان چیزی است که کاربر را گیر می‌اندازد.
     */
    fun heavyFileMessage(bytes: Long): String {
        val mb = (bytes / 1_000_000).coerceAtLeast(1)
        val cap = (MAX_CSV_BYTES / 1_000_000).toInt()
        val bars = (MAX_CSV_BYTES / APPROX_BYTES_PER_BAR / 1_000) * 1_000
        return "فایل $mb مگابایتی از سقف $cap مگابایت بزرگ‌تر است و وارد نشد (سقف برای جا شدن " +
            "در حافظهٔ گوشی گذاشته شده؛ $cap مگابایت ≈ ${grouped(bars)} کندل). سه راه سریع: " +
            "۱) بازهٔ کمتری از dukascopy-node بگیرید (مثلاً یک سال به‌جای پنج سال)، " +
            "۲) تایم‌فریم بالاتر بگیرید (H1 جای M15 حدود ۴ برابر کوچک‌تر است)، " +
            "۳) فایل را با دستور `split` به دو نیم تقسیم کنید و هر نیم را جدا وارد کنید. " +
            "هیچ‌کدام نتیجه را بی‌اعتبار نمی‌کند؛ فقط تعداد معامله‌ها کمتر می‌شود."
    }

    /**
     * پیام وقتی اندازهٔ فایل اعلام نمی‌شود و حین خواندن از سقف می‌گذرد.
     *
     * عمداً کوتاه است و `heavyFileMessage` را صدا نمی‌زند: آن تابع اندازهٔ واقعی را در پیام
     * می‌گذارد و اینجا اندازه‌ای نمی‌دانیم — جملهٔ «۲۴ مگابایت از سقف ۲۴ مگابایت بزرگ‌تر است»
     * بی‌معنا می‌شد.
     */
    fun oversizedWhileReadingMessage(): String {
        val cap = (MAX_CSV_BYTES / 1_000_000).toInt()
        return "فایل از سقف $cap مگابایت بزرگ‌تر است و خواندنش همان‌جا متوقف شد؛ چیزی ذخیره نشد " +
            "و دادهٔ قبلی‌تان دست‌نخورده است. با بازهٔ کمتر، تایم‌فریم بالاتر، یا تقسیم فایل " +
            "با `split` دوباره بسازید."
    }

    private fun grouped(n: Long): String = "%,d".format(n).replace(',', '٬')
}
